"""
个股 AI 分析报告 —— DeepSeek 提示词模板
========================================

沿用 daily_review 的根本约束("只许使用提供的数据"),但对个股再收紧一层:

**禁止一切关于公司本身的叙事** —— 主营业务、产品、行业地位、竞争格局、
管理层、题材概念,一律不许写。原因很实在:这些内容库里一个字都没有,模型
只能从预训练记忆里掏,而记忆既可能过时(公司早就改名/转型/剥离了资产),
又无从核对。大盘复盘里说错一句产业背景无伤大雅,个股报告里说错主营业务
是硬伤,而且正好是读者最容易当真的那部分。

所以这份报告的定位是明确的:**对本平台自有数据的解读**——价格位置、
技术指标、估值分位、以及这只票自己的历史回测实证。不是"研报"。

合规同样是硬约束:陈述式而非指令式,不给目标价,不写"建议买入/卖出"。

要求严格 JSON 输出:
  {"title": ..., "score": 0-100, "trend": "看多|震荡|看空", "content_md": ...}
"""
from __future__ import annotations

import json
from typing import Any, Dict, List

# v1: 首版。五节结构(技术面/估值盈利/策略实证/风险/观察要点),
#     核心差异化是"策略实证"—— 把本站回测引擎跑出来的实测结果交给模型解读
# v2: 首轮实测发现两个漏子:模型会把 ROE 这类衍生指标"估算"出来(标了"估算"
#     的编造仍是编造),以及在五节之外自己续一段"评分理由"。禁令补到衍生指标,
#     评分理由收成独立字段 score_reason
REPORT_PROMPT_VERSION = "v2"


def report_messages(context: Dict[str, Any]) -> List[dict]:
    basic = context.get("basic") or {}
    name = basic.get("name") or basic.get("code") or ""
    code = basic.get("code") or ""

    system = (
        "你是一位严谨的量化数据分析师，只做数据解读，绝不编造事实。"
        "本次对话没有联网能力，你只能使用用户提供的 JSON 数据。\n"
        "三条硬性禁令：\n"
        "1. 禁止描述这家公司的主营业务、产品、行业地位、竞争格局、题材概念、"
        "管理层或任何公司基本面叙事 —— 这些信息不在提供的数据里，"
        "你从记忆里回忆出来的内容可能早已过时且无法核对。"
        "只分析数据本身反映的价格、估值、技术与历史回测特征。\n"
        "2. 禁止编造数据里没有的数字。字段缺失或为 null 表示本平台没有该数据，"
        "如实说明缺失即可，不要用估算或记忆填补。"
        "这条同样适用于**衍生指标**：ROE、毛利率、净利率、PEG、股息率等"
        "凡是需要用未提供的数据算出来的，一律不许出现，"
        "也不要写『约为X』『估算X』——标注了『估算』的编造仍然是编造。\n"
        "3. 禁止写成荐股：不得出现『建议买入』『建议卖出』『加仓』『减仓』"
        "这类指令式表述，不得给出目标价或涨跌预测。"
        "用『技术面显示』『历史回测表明』这样的陈述式。\n"
        "只输出严格的 JSON，不要输出 JSON 之外的任何文字，"
        "不要用 markdown 代码块包裹 JSON。"
    )

    data_str = json.dumps(context, ensure_ascii=False, indent=1)
    user = (
        f"以下是 {name}({code}) 的数据快照（JSON），来自本平台自有行情库与回测引擎。\n\n"
        "字段说明：\n"
        "- basic：代码/名称/上市年限/是否 ST。industry_sw1、industry_sw2 为 null "
        "表示本平台没有该股的行业归属数据，此时不得臆测它属于哪个行业；\n"
        "- quote：close=最新收盘价，pct_change_Nd=近 N 个交易日累计涨跌幅(%)，"
        "high_60d/low_60d=近 60 个交易日收盘最高/最低价，"
        "position_in_60d_pct=当前价在该区间的位置(0=区间最低，100=区间最高)，"
        "volume_ratio_vs_5d=当日成交量/近5日均量（>1 放量，<1 缩量），"
        "turnover_pct=换手率(%)，market_cap=总市值(亿元)，pe_ttm/pb=滚动市盈率/市净率；\n"
        "- technical：ma5/20/60=均线值，price_vs_maN_pct=现价相对该均线的偏离(%)，"
        "ma_alignment=均线排列形态，rsi14=14日RSI，"
        "macd={dif,dea,hist,state}，kdj={k,d,j}；\n"
        "- finance：最近一期财报。report_type=报告期(Q1/Q2/Q3/ANN)，"
        "eps=每股收益，eps_yoy_pct=每股收益同比(%)，bvps=每股净资产。"
        "**只有出现在 JSON 里的字段才有数据**，营收/净利等字段未出现即为本平台缺失，"
        "不要提及也不要估算；\n"
        "- backtest：本平台回测引擎用这只股票近 "
        f"{(context.get('backtest') or {}).get('window_years', 2)} 年的真实日线，"
        "对 9 种内置技术策略逐一实测的结果。"
        "buy_and_hold_return_pct=同期买入持有的收益(%)，是所有策略的对照基准；"
        "strategies=各策略明细(total_return_pct=区间总收益%，win_rate_pct=胜率%，"
        "max_drawdown_pct=最大回撤%，trade_count=完成的往返交易笔数，sharpe=夏普比率)；"
        "best=收益最高的策略；beat_buy_hold_count=跑赢买入持有的策略数量。"
        "backtest 为空对象表示回测数据不足。\n\n"
        f"{data_str}\n\n"
        "请写一份该股的数据解读报告，markdown 格式，总字数 400~600 字，"
        "分以下五节（用 ## 二级标题）：\n"
        "## 技术面 —— 价格在 60 日区间的位置、均线排列、RSI/MACD/KDJ 的状态，"
        "以及量能是放大还是萎缩\n"
        "## 估值与盈利 —— PE/PB 水平与每股收益及其同比；"
        "缺失的指标如实说明，不要绕过也不要估算\n"
        "## 策略实证 —— 本节是重点。对比各策略与买入持有基准，"
        "指出哪类策略在这只票上历史表现更好、哪类明显失效，"
        "并提醒交易笔数过少(如少于5笔)时胜率的统计意义有限。"
        "这是历史回测，不是未来收益的承诺\n"
        "## 风险提示 —— 从数据本身能看出的风险（如高位、超买、高估值、"
        "深回撤、ST、流动性偏低等），不要编造经营层面的风险\n"
        "## 观察要点 —— 后续值得跟踪的数据信号（如某均线的得失、"
        "RSI 回落至某区间、放量与否），陈述式表述，不得给出操作建议\n\n"
        "正文到此为止，五节之外不要再加任何小节、分隔线或总结段落。\n\n"
        "另外单独给出三个字段（不要写进正文）：\n"
        "- score：0-100 的综合评分，只依据以上数据（技术面、估值、回测实证）打分，"
        "50 分为中性；\n"
        "- score_reason：一句话说明评分依据，60 字以内，"
        "依据必须能在正文里找到对应内容；\n"
        "- trend：只能是『看多』『震荡』『看空』三者之一。\n\n"
        "严格按以下 JSON 格式输出，不要有多余文字：\n"
        '{"title": "15-25字的报告标题，概括该股当前数据特征，不得含买卖建议", '
        '"score": 65, "score_reason": "评分依据一句话", "trend": "震荡", '
        '"content_md": "markdown 正文"}'
    )
    return [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]
