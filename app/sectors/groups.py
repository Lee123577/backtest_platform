# 申万Ⅱ/Ⅲ级同名近重复(如 航天装备Ⅱ / 航天装备Ⅲ)—— 去掉级别后缀后去重
_LEVEL_SUFFIX = re.compile(r"[ⅠⅡⅢⅣ]+$")


def normalize_board_name(name: str) -> str:
    """去掉申万级别后缀,用于同名板块去重。"""
    return _LEVEL_SUFFIX.sub("", str(name or "").strip())


def classify(board_name: str) -> Optional[str]:
    """行业板块名 → 6 大分组之一;归不了返回 None。"""
    name = normalize_board_name(board_name)
    if not name:
        return None
    for group, keywords in RULES:
        for kw in keywords:
            if kw in name:
                return group
    return None


