# 红利板块:概念板块里与"高股息/红利"相关的板块名(本地无股息率数据,用其近似)
DIVIDEND_KEYWORDS = ["红利", "高股息", "股息"]


def is_theme(board_name: str) -> bool:
    """是否属于用户关心的题材热点(大小写不敏感)。"""
    n = normalize_board_name(board_name).upper()
    return any(k.upper() in n for k in THEME_KEYWORDS)


def is_dividend(board_name: str) -> bool:
    n = normalize_board_name(board_name)
    return any(k in n for k in DIVIDEND_KEYWORDS)
