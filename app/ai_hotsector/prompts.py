"""
AI 热门板块 —— DeepSeek 提示词模板
====================================

两段式调用（对应"先选板块、再从板块里选强势股"）：
  1. `sector_messages(pick_date)`               → 3 个热门板块
  2. `stock_messages(pick_date, sector_names)`  → 每个板块 3 只最强正股

两次调用都要求严格 JSON 输出（DeepSeek `response_format={"type":"json_object"}`），
避免用正则解析自然语言。
"""
from __future__ import annotations

from datetime import date as _Date
from typing import List

SECTOR_PROMPT_VERSION = "v2"
STOCK_PROMPT_VERSION = "v2"


def sector_messages(pick_date: _Date) -> List[dict]:
    system = (
        "你是一位专注中国A股市场的行业研究员，风格严谨、绝不编造事实。"
        "重要限制：本次对话没有联网/实时行情能力，你看不到今天的任何盘面数据"
        "（涨跌幅、成交额、资金流向、涨停家数等一概不知道）。"
        "判断「热门板块」时只能依据你已掌握的、相对稳定的事实"
        "——近期已知的产业趋势、政策方向、技术/产品周期性催化剂等——"
        "绝对不允许编造具体的当日行情数字（如「今日大涨」「资金净流入居前」"
        "「涨停家数众多」之类），一旦无法确认就不要写这类描述，"
        "改写板块本身的产业逻辑/催化剂。"
        "只输出严格的 JSON，不要输出任何 JSON 之外的文字，不要用 markdown 代码块包裹。"
    )
    user = (
        f"背景：今天是 {pick_date.isoformat()}（A 股交易日），已收盘，"
        "但你没有当天实时行情数据。\n"
        "请给出你认为当前最值得关注的 3 个行业/概念板块（例如：人工智能、半导体、机器人、"
        "创新药、军工等具体行业或概念，不要用'大盘'这种笼统说法），"
        "按你判断的关注度从高到低排序。\n"
        "reason 请基于产业趋势、政策方向、技术/产品周期等可考证的信息展开，20-50字，"
        "不得包含任何具体的当日行情数字（涨跌幅/资金流向/涨停家数等）。\n\n"
        "严格按以下 JSON 格式输出，不要有多余文字：\n"
        '{"sectors": [{"name": "板块名称", "reason": "20-50字入选理由,不含当日行情数据"}, '
        '... 恰好3个]}'
    )
    return [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]


def stock_messages(pick_date: _Date, sector_names: List[str]) -> List[dict]:
    system = (
        "你是一位专注中国A股市场的选股研究员，风格严谨、绝不编造事实。"
        "重要限制：本次对话没有联网/实时行情能力，你看不到今天的任何盘面数据"
        "（涨跌幅、是否涨停、成交量、资金流向等一概不知道）。"
        "选股和写理由时只能依据你已掌握的、相对稳定的事实"
        "——公司在该板块的产业地位、主营业务、技术布局、历史市场认知度等——"
        "绝对不允许编造具体的当日行情数字（如「今日涨停」「涨超8%」「资金净流入居前」之类），"
        "一旦无法确认就不要写这类描述，改写公司本身的基本面/产业逻辑。\n"
        "选股范围限制：只能给出真实存在、目前正常上市交易的A股代码"
        "（沪深京任意板块均可，但排除ST/*ST/退市整理期/已停牌股票），"
        "代码必须是6位数字且与公司名称真实对应；如果记不清某公司的准确代码，"
        "宁可换一只你更确定的股票，也不要编造代码。"
        "同一只股票不允许在不同板块重复出现。"
        "只输出严格的 JSON，不要输出任何 JSON 之外的文字，不要用 markdown 代码块包裹。"
    )
    sectors_str = "、".join(sector_names)
    user = (
        f"背景：今天是 {pick_date.isoformat()}（A 股交易日），已收盘，"
        "但你没有当天实时行情数据。\n"
        f"针对以下 3 个板块：{sectors_str}，"
        "请分别给出每个板块内最具代表性、最能体现该板块投资逻辑的 3 只正股，"
        "按你判断的代表性/龙头程度从高到低排序。\n"
        "reason 请基于产业地位、核心业务、技术卡位等可考证的信息展开，20-50字，"
        "不得包含任何具体的当日涨跌幅/是否涨停/资金流向等你无法确认的数据。\n\n"
        "严格按以下 JSON 格式输出，不要有多余文字：\n"
        '{"sectors": ['
        '{"name": "板块名称(必须与给定板块名一致)", '
        '"stocks": [{"code": "6位数字股票代码", "name": "与代码真实对应的股票名称", '
        '"reason": "20-50字入选理由,不含当日行情数据"}, ... 恰好3个]}, '
        "... 覆盖全部给定板块，每个板块都必须给满3只]}"
    )
    return [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]
