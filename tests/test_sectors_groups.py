"""
板块分类映射测试
================
用例里的板块名全部取自东财接口的**真实返回**(非杜撰),重点锁死关键词
顺序冲突 —— 这些是实测踩到过的坑:
  电力设备→科技(不能被"电力"抢到公用)、电子化学品→科技(不能被"化工"抢到周期)、
  房产租赁经纪→公用(不能被"租赁"抢到金融)、品牌消费电子→科技(不能被"电器"抢到消费)
"""
import pytest

from app.sectors.groups import (
    GROUP_NAMES, classify, is_dividend, is_theme, normalize_board_name,
)


# ── 级别后缀归一 ─────────────────────────────────────────────────────────────

@pytest.mark.parametrize("raw,want", [
    ("专业连锁Ⅲ", "专业连锁"),
    ("专业连锁Ⅱ", "专业连锁"),
    ("体育Ⅲ", "体育"),
    ("传媒", "传媒"),
    ("  医疗服务 ", "医疗服务"),
])
def test_normalize_board_name(raw, want):
    assert normalize_board_name(raw) == want


def test_level_variants_map_to_same_group():
    assert classify("专业连锁Ⅱ") == classify("专业连锁Ⅲ") == "消费"


# ── 关键词顺序冲突(实测踩过的坑) ────────────────────────────────────────────

@pytest.mark.parametrize("name,want", [
    ("电力设备", "科技成长"),      # 不能被"电力"抢到公用防御
    ("电池", "科技成长"),
    ("光伏设备", "科技成长"),
    ("电力行业", "公用防御"),      # 真正的电力才归公用
    ("电子化学品", "科技成长"),    # 不能被"化工"抢到周期资源
    ("房产租赁经纪", "公用防御"),  # 不能被"租赁"抢到金融
    ("品牌消费电子", "科技成长"),  # 不能被"电器"抢到消费
    ("融资租赁", "金融"),
    ("农药化肥", "周期资源"),      # 不能被裸"药"抢到医药(实测踩到过)
    ("生物制药", "医药"),
    ("中成药", "医药"),
    ("金融行业", "金融"),          # 新浪把金融合成一个板块,不拆银行/证券/保险
])
def test_keyword_conflicts(name, want):
    assert classify(name) == want


# ── 真实板块名(取自东财接口实际返回) ────────────────────────────────────────

